# 코퍼스를 반복하여 볼륨을 높임 (최소 5만 자 이상 확보)
def get_bundled_corpus(min_chars: int = 60000) -> str:
    base = KOREAN_CORPUS.strip()
    result = base
    while len(result) < min_chars:
        result = result + "\n\n" + base
    return result


def try_download_hf_korean(n_samples: int = 3000) -> str | None:
    """
    HuggingFace datasets에서 한국어 위키백과 텍스트 다운로드 시도.
    실패 시 None 반환.
    """
    try:
        from datasets import load_dataset
        print("HuggingFace datasets로 한국어 위키백과 다운로드 시도...")
        # 'wikimedia/wikipedia' 2023-11 snapshot, ko language
        ds = load_dataset(
            "wikimedia/wikipedia",
            "20231101.ko",
            split="train",
            streaming=True,
        )
        texts = []
        total_chars = 0
        for i, sample in enumerate(ds):
            if i >= n_samples:
                break
            text = sample.get("text", "")
            if len(text) > 100:  # 너무 짧은 문서 제외
                texts.append(text)
                total_chars += len(text)
            if total_chars > 2_000_000:  # 200만 자 목표 (원래 200K → 10배 확대)
                break
        if texts:
            print(f"  다운로드 완료: {len(texts)}개 문서, {total_chars:,}자")
            return "\n\n".join(texts)
        return None
    except Exception as e:
        print(f"  HF 다운로드 실패: {e}")
        return None


def main():
    parser = argparse.ArgumentParser(description="한국어 코퍼스로 BPE 학습 + 바이너리 생성")
    parser.add_argument("--vocab-size", type=int, default=2048,
                        help="BPE vocab size (기본: 2048, 한국어 권장 2048~8192)")
    parser.add_argument("--val-frac", type=float, default=0.1,
                        help="validation 비율")
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--no-download", action="store_true",
                        help="HF 다운로드 시도 없이 번들 코퍼스만 사용")
    parser.add_argument("--n-samples", type=int, default=3000,
                        help="HF에서 가져올 최대 문서 수")
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)

    # ── 1) 텍스트 획득 ──────────────────────────────────────────
    text = None
    corpus_path = data_dir / "korean_corpus.txt"

    if not args.no_download:
        t0 = time.time()
        text = try_download_hf_korean(args.n_samples)
        if text:
            corpus_path.write_text(text, encoding="utf-8")
            print(f"  저장: {corpus_path}  ({time.time()-t0:.1f}s)")

    if text is None:
        # 이미 저장된 파일이 있으면 재사용
        if corpus_path.exists():
            print(f"기존 파일 사용: {corpus_path}")
            text = corpus_path.read_text(encoding="utf-8")
        else:
            print("번들 한국어 코퍼스 사용 (HF 다운로드 없음)")
            text = get_bundled_corpus(min_chars=60000)
            corpus_path.write_text(text, encoding="utf-8")
            print(f"  저장: {corpus_path}  ({len(text):,}자)")

    print(f"\n코퍼스: {len(text):,}자")

    # ── 2) BPE 학습 ─────────────────────────────────────────────
    print(f"\nBPE 학습 (vocab_size={args.vocab_size})...")
    tok = BPETokenizer()
    tok.train(text, vocab_size=args.vocab_size, verbose=True)

    # ── 3) 특수 토큰 ─────────────────────────────────────────────
    tok.register_special_tokens(SPECIAL_TOKENS)
    print(f"특수 토큰 추가 후 vocab size: {tok.vocab_size}")
    assert tok.vocab_size < 2**16, "vocab_size 65535 초과"

    # ── 4) 토크나이저 저장 ────────────────────────────────────────
    tokenizer_path = data_dir / "tokenizer.json"
    tok.save(tokenizer_path)
    print(f"토크나이저 저장: {tokenizer_path}")

    # ── 5) 인코딩 ────────────────────────────────────────────────
    print("\n전체 코퍼스 인코딩 중...")
    ids = tok.encode(text)
    n = len(ids)
    ratio = len(text) / n if n else 0
    print(f"인코딩 완료: {n:,} 토큰  (압축률 {ratio:.2f} 자/토큰)")

    # ── 6) train/val split ───────────────────────────────────────
    n_val = int(n * args.val_frac)
    train_ids = ids[:-n_val] if n_val > 0 else ids
    val_ids = ids[-n_val:] if n_val > 0 else []

    train_arr = np.array(train_ids, dtype=np.uint16)
    val_arr = np.array(val_ids, dtype=np.uint16)
    train_arr.tofile(data_dir / "train.bin")
    val_arr.tofile(data_dir / "val.bin")
    print(f"train.bin: {len(train_arr):,} 토큰")
    print(f"val.bin:   {len(val_arr):,} 토큰")

    # ── 7) 메타데이터 ────────────────────────────────────────────
    meta = {
        "vocab_size": tok.vocab_size,
        "n_train_tokens": len(train_arr),
        "n_val_tokens": len(val_arr),
        "special_tokens": tok.special_tokens,
        "source_file": str(corpus_path),
        "source_chars": len(text),
        "language": "ko",
    }
    (data_dir / "meta.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=2)
    )

    print(f"\n✅ 준비 완료. data/ 폴더:")
    print(f"   tokenizer.json, train.bin, val.bin, meta.json")
    print(f"\n다음 단계: python train.py --max-iters 5000 --n-layer 6 --n-head 6 --n-embd 384 --block-size 128 --batch-size 16")


if __name__ == "__main__":
    main()
